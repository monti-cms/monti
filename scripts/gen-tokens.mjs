// Generates the admin's design tokens from the design system's `packages/ui/tokens/tokens.json`. Run from the repo root: `pnpm gen:tokens`.
//
// Writes four files, all generated, never edited by hand (a test in `@monti-cms/ui` fails when they differ from this script's output):
//   - `packages/ui/styles/tokens.css`       the values: every token as a `--monti-*` custom property, light and dark.
//   - `packages/ui/styles/theme.css`        the Tailwind names: the part between the BEGIN and END markers (`bg-monti-tool`, `gap-monti-12`, `text-monti-body` ...).
//                                           The rest of the file is hand-written and stays as it is.
//   - `packages/ui/src/tokens.generated.ts` the options of the layout parts (`gap={12}`, `background="tool"`, `width="sheet"`): each key is a token name,
//                                           each value the class, written out whole so Tailwind finds it.
//   - `packages/ui/.storybook/manager-theme.generated.ts` the colors, fonts and radii of Storybook's own chrome (sidebar, toolbar, panels), as literal
//                                           values: its theming runs color math on them, so it cannot read CSS variables.
//
// The class names follow the design system's role names one to one, with a `monti-` prefix on every class: the admin runs on the site's own pages, next
// to the site's Tailwind classes, so none of ours may look like a Tailwind class.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TOKENS_JSON = path.join(ROOT, "packages/ui/tokens/tokens.json");
const TOKENS_CSS = path.join(ROOT, "packages/ui/styles/tokens.css");
const THEME_CSS = path.join(ROOT, "packages/ui/styles/theme.css");
const TOKENS_TS = path.join(ROOT, "packages/ui/src/tokens.generated.ts");
const MANAGER_THEME_TS = path.join(ROOT, "packages/ui/.storybook/manager-theme.generated.ts");

export const BEGIN =
	"/* BEGIN generated by scripts/gen-tokens.mjs from packages/ui/tokens/tokens.json. Do not edit by hand. */";
export const END = "/* END generated */";

/** Where the admin sits in a page. Zero specificity, so a site's own `:root { --monti-gray-4: ... }` or `.dark { ... }` wins in any stylesheet order. */
const LIGHT = ":where(html:has(.monti-admin))";
const DARK = ':where(html:is(.dark, [data-theme="dark"]):has(.monti-admin))';

/** The admin bundle ships its fonts under these names (`bundledFonts` in `scripts/build-styles.mjs`), so they never collide with a site's own copy. */
const BUNDLED_FACES = { Pretendard: '"Monti Pretendard"', '"IBM Plex Mono"': '"Monti Plex Mono"' };

/**
 * A height class carries its token's name whole (`height-icon-button` is `h-monti-icon-button`), so a 32px button size (`size-monti-icon-button`) can never
 * be mistaken for a 16px glyph size (`size-monti-icon-md`). The heights of square controls also get a `size-monti-*` class.
 */
const SQUARE = new Set(["control-md", "control-sm", "icon-button"]);

const ref = (value) => value.replace(/\{([\w-]+)\}/g, "var(--monti-$1)");
const strip = (name, prefix) => name.slice(prefix.length);
/** The type style `text-display` as the role `display`. */
const roleOf = (style) => strip(style.name, "text-");

/** The font stack with the bundled faces under the admin's names. */
function fontStack(stack) {
	return stack
		.split(/,\s*(?=(?:[^"]*"[^"]*")*[^"]*$)/)
		.map((face) => BUNDLED_FACES[face.trim()] ?? face.trim())
		.join(", ");
}

/** The values file. */
function tokensCss(json) {
	const colors = json.color.tokens;
	const shadows = json.shadow.tokens;
	const themed = (token, mode) => `--monti-${token.name}: ${ref(token.value[mode])};`;
	const plain = (group) => json[group].tokens.map((token) => `--monti-${token.name}: ${token.value};`);

	const type = json.type.groups.flatMap((group) =>
		group.styles.flatMap((style) => {
			const role = roleOf(style);
			return [
				`--monti-text-${role}-size: ${style.fontSize};`,
				`--monti-text-${role}-line: ${style.lineHeight};`,
				`--monti-text-${role}-weight: ${style.fontWeight};`,
				`--monti-text-${role}-tracking: ${style.letterSpacing ?? "0em"};`,
			];
		}),
	);
	const fonts = Object.entries(json.type.families).map(([name, stack]) => `--monti-font-${name}: ${fontStack(stack)};`);
	// A role with the same value in both modes (usually a reference to a scale step) is declared once, so overriding a step restyles every role on it.
	const differs = [...colors, ...shadows].filter((token) => token.value.light !== token.value.dark);

	const block = (selector, lines) => `${selector} {\n${lines.map((line) => `\t${line}`).join("\n")}\n}\n`;
	return [
		[
			"/*",
			" * The values of the design system's tokens (names in `theme.css`). GENERATED by `scripts/gen-tokens.mjs` from `tokens/tokens.json`:",
			" * edit that file and run `pnpm gen:tokens`. Read at build time by the admin bundle; a site overrides any `--monti-*` variable on `:root`,",
			' * `.dark` or `[data-theme="dark"]`. The host\'s own tokens are left untouched. Popups and menus are portaled to body, so the values apply',
			" * to the whole document that contains the admin. The defaults have zero specificity (`:where()`), so a site's override wins in any stylesheet order.",
			" */",
			"",
		].join("\n"),
		block(LIGHT, [
			"color-scheme: light;",
			...colors.map((token) => themed(token, "light")),
			...plain("spacing"),
			...plain("radius"),
			...plain("height"),
			...plain("width"),
			...plain("size"),
			...shadows.map((token) => themed(token, "light")),
			...type,
			...fonts,
		]),
		block(DARK, ["color-scheme: dark;", ...differs.map((token) => themed(token, "dark"))]),
	].join("\n");
}

/** The `--property-monti-name: value;` lines of the Tailwind theme, one per class name. */
function themeLines(json) {
	const out = [];
	const add = (property, name, value) => out.push(`\t--${property}-monti-${name}: ${value};`);
	const section = (title) => out.push("", `\t/* ${title} */`);

	const roles = (prefix) =>
		json.color.tokens.filter((token) => token.name.startsWith(prefix)).map((token) => strip(token.name, prefix));
	const bg = roles("bg-");
	const fg = roles("fg-");
	const border = roles("border-");
	const of = (kind, role) => `var(--monti-${kind}-${role})`;

	section(
		"Colors. Each property has its own namespace, so the class says what it paints: bg-monti-<role>, text-monti-<role>, border-monti-<role> ...",
	);
	for (const role of bg) add("background-color", role, of("bg", role));
	// A 1px divider drawn as a box (separators, the split button's seam).
	add("background-color", "divider", of("border", "muted"));
	for (const role of fg) add("text-color", role, of("fg", role));
	// Lines, rings, outlines and decorations take the border roles and the text roles no border role has the name of (`default` and `muted` are the border's).
	const lines = [
		...border.map((role) => [role, "border"]),
		...fg.filter((role) => !border.includes(role)).map((role) => [role, "fg"]),
	];
	for (const property of ["border-color", "ring-color", "outline-color", "text-decoration-color"]) {
		for (const [role, kind] of lines) add(property, role, of(kind, role));
	}
	// The caret and the icons drawn with `fill-` and `stroke-` follow the text roles; a stroke also takes the border roles the text has no name for.
	for (const property of ["caret-color", "fill", "stroke"]) for (const role of fg) add(property, role, of("fg", role));
	for (const role of border.filter((role) => !fg.includes(role))) add("stroke", role, of("border", role));
	add("stroke", "divider", of("border", "muted"));
	add("ring-offset-color", "page", of("bg", "page"));

	section(
		"Spacing: gaps, padding and margins take the scale (gap-monti-12, px-monti-16, -mt-monti-4). Tailwind's own numbers stay for sizes.",
	);
	for (const { name } of json.spacing.tokens) add("spacing", strip(name, "space-"), `var(--monti-${name})`);

	section("Corner radius (rounded-monti-sm ... rounded-monti-full).");
	for (const { name } of json.radius.tokens) add("radius", strip(name, "radius-"), `var(--monti-${name})`);

	section(
		"Heights of controls and bars (h-monti-*, min-h-monti-*); the square ones also size-monti-*. Glyph sizes are size-monti-icon-xs to -lg; the 32px icon button is size-monti-icon-button.",
	);
	for (const { name } of json.height.tokens) {
		const role = strip(name, "height-");
		add("height", role, `var(--monti-${name})`);
		if (SQUARE.has(role)) add("size", role, `var(--monti-${name})`);
	}
	for (const { name } of json.size.tokens) add("size", strip(name, "size-"), `var(--monti-${name})`);

	section("Widths of columns, panels and sheets (w-monti-*, min-w-monti-*, max-w-monti-*).");
	for (const { name } of json.width.tokens) add("container", strip(name, "width-"), `var(--monti-${name})`);

	section("Shadows: floating surfaces only. The rest of the design is flat.");
	for (const { name } of json.shadow.tokens) add("shadow", strip(name, "shadow-"), `var(--monti-${name})`);

	section("Fonts. `font-sans` and `font-mono` follow the admin tokens, never the host's.");
	for (const family of Object.keys(json.type.families)) out.push(`\t--font-${family}: var(--monti-font-${family});`);
	return out.slice(1);
}

/**
 * The type roles as utilities: size, line height, weight, letter spacing and font family together (Tailwind's `--text-*` theme cannot set the family). A mono
 * role is always mono. A sans role takes the family from `--monti-family` (`font-mono` sets it, on its own element only: `theme.css` makes it a property that
 * is not inherited) and is sans otherwise, so `font-mono` beside `md:text-monti-body` still wins, whatever order the two rules come in, and a sans role inside
 * a mono parent is sans.
 */
function typeUtilities(json) {
	return json.type.groups.flatMap((group) =>
		group.styles.map((style) => {
			const role = roleOf(style);
			return [
				`/* ${style.fontSize}/${style.lineHeight} ${style.fontWeight}. ${style.usage} */`,
				`@utility text-monti-${role} {`,
				group.family === "sans"
					? "\tfont-family: var(--monti-family, var(--monti-font-sans));"
					: `\tfont-family: var(--monti-font-${group.family});`,
				`\tfont-size: var(--monti-text-${role}-size);`,
				`\tline-height: var(--monti-text-${role}-line);`,
				`\tfont-weight: var(--monti-text-${role}-weight);`,
				`\tletter-spacing: var(--monti-text-${role}-tracking);`,
				"}",
			].join("\n");
		}),
	);
}

/** What goes between the markers of `theme.css`. */
function themeBlock(json) {
	return [
		BEGIN,
		"@theme inline {",
		"\t/* These namespaces hold the design system's names only: Tailwind's own `rounded-*` and `shadow-*` produce no CSS. */",
		"\t--radius-*: initial;",
		"\t--shadow-*: initial;",
		"",
		...themeLines(json),
		"}",
		"",
		typeUtilities(json).join("\n\n"),
		END,
	].join("\n");
}

/** Background roles that are not surfaces of a box: the scrim behind a dialog and the fill of the delete pill. */
const NOT_A_SURFACE = new Set(["backdrop", "danger-emphasis"]);

/** The options of the layout parts, by token name: `export const NAME = { key: "class" } as const;` with every class written out whole. */
function layoutModule(json) {
	const spacing = [0, ...json.spacing.tokens.map(({ name }) => Number(strip(name, "space-")))];
	const names = (group, prefix) => json[group].tokens.map(({ name }) => strip(name, prefix));
	const heights = names("height", "height-");
	const widths = names("width", "width-");
	const surfaces = json.color.tokens
		.filter(({ name }) => name.startsWith("bg-"))
		.map(({ name }) => strip(name, "bg-"))
		.filter((role) => !NOT_A_SURFACE.has(role));

	const key = (value) =>
		/^[A-Za-z_$][\w$]*$/.test(String(value)) || typeof value === "number" ? String(value) : JSON.stringify(value);
	const entries = (keys, make) => keys.map((value) => `\t${key(value)}: ${JSON.stringify(make(value))},`);
	const block = (doc, name, lines) => `/** ${doc} */\nexport const ${name} = {\n${lines.join("\n")}\n} as const;\n`;
	const scale = (name, prefix, doc) =>
		block(
			doc,
			name,
			entries(spacing, (step) => (step === 0 ? `${prefix}-0` : `${prefix}-monti-${step}`)),
		);

	return [
		"// GENERATED by `scripts/gen-tokens.mjs` from `tokens/tokens.json`: edit that file and run `pnpm gen:tokens`.",
		"// Every class is written out whole, so Tailwind finds it when it scans this file.",
		"",
		scale("GAP", "gap", "The space between children, by the px step of the spacing scale."),
		scale("PADDING", "p", "Padding on every side, by the px step of the spacing scale."),
		scale("PADDING_X", "px", "Padding left and right."),
		scale("PADDING_Y", "py", "Padding above and below."),
		scale("PADDING_TOP", "pt", "Padding above."),
		scale("PADDING_BOTTOM", "pb", "Padding below."),
		block(
			"Surfaces, by background role. The black one carries its own text color, so what is written on it can be read.",
			"BACKGROUND",
			entries(surfaces, (role) =>
				role === "emphasis" ? "bg-monti-emphasis text-monti-on-emphasis" : `bg-monti-${role}`,
			),
		),
		block(
			"Corner radius.",
			"RADIUS",
			entries(names("radius", "radius-"), (role) => `rounded-monti-${role}`),
		),
		block(
			"Widths of columns, panels and sheets.",
			"WIDTH",
			entries(widths, (role) => `w-monti-${role}`),
		),
		block(
			"The widest a box grows, by the same width tokens.",
			"MAX_WIDTH",
			entries(widths, (role) => `max-w-monti-${role}`),
		),
		block(
			"Heights of controls and bars.",
			"HEIGHT",
			entries(heights, (role) => `h-monti-${role}`),
		),
		block(
			"The least height of a box, by the same height tokens.",
			"MIN_HEIGHT",
			entries(heights, (role) => `min-h-monti-${role}`),
		),
		"/** The px steps of the spacing scale (and `0`). */",
		"export type Spacing = keyof typeof GAP;",
		"/** The background roles. */",
		"export type Background = keyof typeof BACKGROUND;",
		"",
	].join("\n");
}

/** Storybook's theme variable for each design role: the manager (its sidebar, toolbar and panels) is dressed in the same roles as the admin. */
const MANAGER_ROLES = {
	colorPrimary: "bg-emphasis",
	colorSecondary: "bg-emphasis",
	appBg: "bg-tool",
	appContentBg: "bg-page",
	appHoverBg: "bg-muted",
	appPreviewBg: "bg-page",
	appBorderColor: "border-default",
	textColor: "fg-default",
	textInverseColor: "fg-on-emphasis",
	textMutedColor: "fg-muted",
	barTextColor: "fg-muted",
	barHoverColor: "fg-default",
	barSelectedColor: "fg-default",
	barBg: "bg-tool",
	buttonBg: "bg-page",
	buttonBorder: "border-default",
	booleanBg: "border-default",
	booleanSelectedBg: "bg-emphasis",
	inputBg: "bg-page",
	inputBorder: "border-strong",
	inputTextColor: "fg-default",
};

/** Storybook's theme values, in light and dark, with every reference resolved to the hex it points at. */
function managerThemeModule(json) {
	const tokens = new Map(json.color.tokens.map((token) => [token.name, token.value]));
	const resolve = (name, mode) => {
		const value = tokens.get(name)?.[mode];
		if (value === undefined) throw new Error(`manager theme: no color token ${name}`);
		const reference = /^\{([\w-]+)\}$/.exec(value);
		return reference ? resolve(reference[1], mode) : value;
	};
	// Biome prefers single quotes around a string that holds double quotes (a font stack), and the file is checked against this output.
	const quote = (text) => (text.includes('"') && !text.includes("'") ? `'${text}'` : JSON.stringify(text));
	const radius = (name) => Number.parseInt(json.radius.tokens.find((token) => token.name === name).value, 10);
	const mode = (id) =>
		[
			...Object.entries(MANAGER_ROLES).map(([key, role]) => `\t\t${key}: ${quote(resolve(role, id))},`),
			`\t\tfontBase: ${quote(fontStack(json.type.families.sans))},`,
			`\t\tfontCode: ${quote(fontStack(json.type.families.mono))},`,
			`\t\tappBorderRadius: ${radius("radius-lg")},`,
			`\t\tinputBorderRadius: ${radius("radius-md")},`,
		].join("\n");
	return [
		"// GENERATED by `scripts/gen-tokens.mjs` from `tokens/tokens.json`: edit that file and run `pnpm gen:tokens`.",
		"// Storybook's theming does color math on these, so they are literal values, not CSS variables.",
		"",
		"export const MANAGER_THEME = {",
		`\tlight: {\n${mode("light")}\n\t},`,
		`\tdark: {\n${mode("dark")}\n\t},`,
		"} as const;",
		"",
	].join("\n");
}

/** The generated files' text, from `tokens.json` and the current `theme.css` (whose hand-written parts are kept). */
export function generate({
	json = JSON.parse(readFileSync(TOKENS_JSON, "utf8")),
	themeSource = readFileSync(THEME_CSS, "utf8"),
} = {}) {
	const start = themeSource.indexOf(BEGIN);
	const end = themeSource.indexOf(END);
	if (start === -1 || end === -1 || end < start) throw new Error(`theme.css needs the markers:\n${BEGIN}\n${END}`);
	return {
		tokens: tokensCss(json),
		layout: layoutModule(json),
		managerTheme: managerThemeModule(json),
		theme: themeSource.slice(0, start) + themeBlock(json) + themeSource.slice(end + END.length),
	};
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
	const { tokens, theme, layout, managerTheme } = generate();
	writeFileSync(TOKENS_CSS, tokens);
	writeFileSync(THEME_CSS, theme);
	writeFileSync(TOKENS_TS, layout);
	writeFileSync(MANAGER_THEME_TS, managerTheme);
	console.log(
		"wrote packages/ui/styles/tokens.css, packages/ui/styles/theme.css, packages/ui/src/tokens.generated.ts and packages/ui/.storybook/manager-theme.generated.ts",
	);
}
