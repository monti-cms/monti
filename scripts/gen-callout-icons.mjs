// Generates the callout's title icons for the site's CSS from the Carbon glyphs the editor's kind button draws: one map of kinds to glyphs
// (`packages/blocks/blocks/callout/kind-icons.ts`), one source of the drawings (`@carbon/icons-react`). Run from the repo root: `pnpm gen:callout-icons`.
// `pnpm gen:callout-icons --check` (CI) writes nothing and fails when the file differs from what the script would write.
//
// Writes `packages/blocks/blocks/callout/icon-masks.generated.ts`: for each kind a CSS `url(...)` of the glyph as an SVG, used as the title icon's mask.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const KINDS = path.join(ROOT, "packages/blocks/blocks/callout/kind-icons.ts");
const OUT = path.join(ROOT, "packages/blocks/blocks/callout/icon-masks.generated.ts");

const requireFromUi = createRequire(path.join(ROOT, "packages/ui/package.json"));
const React = requireFromUi("react");
const { renderToStaticMarkup } = requireFromUi("react-dom/server");
const carbon = requireFromUi("@carbon/icons-react");

/** The kinds and the Carbon glyph of each: the object literal of `kind-icons.ts`. */
const kinds = Object.fromEntries(
	[...readFileSync(KINDS, "utf8").matchAll(/^\t(\w+): "(\w+)",$/gm)].map(([, kind, glyph]) => [kind, glyph]),
);
if (Object.keys(kinds).length === 0) throw new Error("kind-icons.ts holds no kinds");

const mask = (glyph) => {
	const Icon = carbon[glyph];
	if (!Icon) throw new Error(`@carbon/icons-react has no ${glyph}`);
	const markup = renderToStaticMarkup(React.createElement(Icon, { size: 16 }));
	const [, open, inner] = /<svg([^>]*)>([\s\S]*)<\/svg>/.exec(markup) ?? [];
	// The editor draws the glyph at 16px, where Carbon has its own 16px drawing for some of them: the one the markup holds, with its own viewBox.
	const viewBox = /viewBox="([^"]*)"/.exec(open ?? "")?.[1] ?? "0 0 32 32";
	const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='${viewBox}' fill='currentColor'>${(inner ?? "").replaceAll('"', "'")}</svg>`;
	return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
};

const text = [
	"// GENERATED by `scripts/gen-callout-icons.mjs` from `kind-icons.ts`: edit that file and run `pnpm gen:callout-icons`.",
	"// The Carbon glyph of each kind as a CSS mask, the same drawing the editor's kind button shows.",
	"",
	`export const ICON_MASKS = {`,
	...Object.entries(kinds).map(([kind, glyph]) => `\t${kind}: ${JSON.stringify(mask(glyph))},`),
	"} as const;",
	"",
].join("\n");

const biome = path.join(ROOT, "node_modules/.bin/biome");
const formatted = execFileSync(biome, ["check", "--write", `--stdin-file-path=${path.relative(ROOT, OUT)}`], {
	cwd: ROOT,
	input: text,
	encoding: "utf8",
	stdio: ["pipe", "pipe", "pipe"],
});

if (process.argv.includes("--check")) {
	if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== formatted) {
		console.error(
			"gen:callout-icons --check: icon-masks.generated.ts differs from what scripts/gen-callout-icons.mjs writes (run `pnpm gen:callout-icons`).",
		);
		process.exit(1);
	}
	console.log("gen:callout-icons --check: icon-masks.generated.ts matches the glyphs");
} else {
	writeFileSync(OUT, formatted);
	console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
