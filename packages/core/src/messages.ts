import type { Message } from "./operation";

type Dictionary = Record<string, string>;

/** A message dictionary: the same keys in English and Korean. The admin shows a `Message` by its key in the admin's language (doc 15). */
export type MessageBundle = { namespace: string; messages: { en: Dictionary; ko: Dictionary } };

export function defineMessages<Bundle extends MessageBundle>(bundle: Bundle): Bundle {
	return bundle;
}

/** A message's text in a language: the key's text with `{name}` filled in. A key no dictionary has comes back as itself. */
export function formatMessage(bundles: MessageBundle[], language: "en" | "ko", message: Message): string {
	const text = bundles.map((bundle) => bundle.messages[language][message.key]).find((found) => found !== undefined);
	if (text === undefined) return message.key;
	return text.replace(/\{(\w+)\}/g, (whole, name: string) => String(message.values?.[name] ?? whole));
}

